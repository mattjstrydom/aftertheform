// Runs after `next build` (npm "postbuild"). Adds what a static export can't produce on its own:
// - out/_headers: security headers on every page and file (scripts/security-headers.mjs), long caching for hashed
//   files, image/png for the extension-less icon files, and X-Robots-Tag: noindex on non-production builds
// - out/favicon.ico: the generated icon wrapped in an ICO container (browsers request /favicon.ico regardless)
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { securityHeaders } from "./security-headers.mjs";

const out = new URL("../out/", import.meta.url);
for (const f of ["index.html", "404.html", "icon"]) {
  if (!existsSync(new URL(f, out))) throw new Error(`out/${f} is missing: did next build run with output: "export"?`);
}

// Same decision the pages made: a noindex build has <meta name="robots" content="noindex..."> (site.indexable).
const indexable = !/<meta name="robots" content="noindex/.test(readFileSync(new URL("index.html", out), "utf8"));

const rule = (path, headers) => [path, ...headers.map(([k, v]) => `  ${k}: ${v}`)].join("\n");
const headers = [
  "# Generated by scripts/cf-postbuild.mjs. Do not edit out/_headers by hand.",
  rule("/_next/static/*", [["Cache-Control", "public, max-age=31536000, immutable"]]),
  rule("/_img/*", [["Cache-Control", "public, max-age=86400"]]),
  rule("/icon", [["Content-Type", "image/png"]]),
  rule("/apple-icon", [["Content-Type", "image/png"]]),
  rule("/*", securityHeaders(indexable)),
].join("\n\n");
writeFileSync(new URL("_headers", out), headers + "\n");

// ICO with one embedded PNG entry (supported by every current browser).
const png = readFileSync(new URL("icon", out));
const w = png.readUInt32BE(16), h = png.readUInt32BE(20);
const ico = Buffer.alloc(22);
ico.writeUInt16LE(0, 0); ico.writeUInt16LE(1, 2); ico.writeUInt16LE(1, 4); // reserved, type icon, 1 image
ico.writeUInt8(w >= 256 ? 0 : w, 6); ico.writeUInt8(h >= 256 ? 0 : h, 7);
ico.writeUInt16LE(1, 10); ico.writeUInt16LE(32, 12); // planes, bits per pixel
ico.writeUInt32LE(png.length, 14); ico.writeUInt32LE(22, 18); // size, offset
writeFileSync(new URL("favicon.ico", out), Buffer.concat([ico, png]));

console.log(`cf-postbuild: out/_headers (${indexable ? "indexable" : "noindex"}), out/favicon.ico (${w}x${h})`);
